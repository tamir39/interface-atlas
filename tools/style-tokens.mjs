import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'Usage: node tools/style-tokens.mjs [--check]');
const catalog = JSON.parse(await readFile(path.join(root, 'catalog/themes.json'), 'utf8'));
// A bounded token projection, not a copy of each theme's layouts or component behavior.
// Literal geometry is traced to a named source selector instead of invented theme tokens.
const config = {
  editorial: { font: '--sans', display: '--serif', mono: '--mono', card: '--specimen-radius', control: '--specimen-input-radius' },
  swiss: { font: '--sans', display: '--sans', mono: '--mono', card: ['.project-art', '2px'], control: ['input[type="text"], select', '2px'] },
  precision: { font: '--sans', display: '--sans', mono: '--mono', card: ['.preview-settings', '4px'], control: ['.button', '4px'] },
  play: { font: '--font-sans', display: '--font-sans', mono: '--font-mono', card: '--panel-radius', control: '--control-radius' },
  botanical: { font: '--body-font', display: '--display-font', mono: '--mono-font', card: '--panel-radius', control: '--control-radius' },
  blueprint: { font: '--body-font', display: '--display-font', mono: '--display-font', card: '--radius-panel', control: '--radius-control' },
  pulse: { font: '--body-font', display: '--display-font', mono: '--mono-font', card: '--panel-radius', control: '--control-radius' },
  gallery: { font: 'font-family', display: 'font-family', mono: ['Atlas specimen fallback', 'Consolas, monospace'], card: ['.preview-settings', '4px'], control: ['button, select, input[type="search"], input[type="text"]', '4px'] },
  layered: { font: 'font-family', display: 'font-family', mono: ['Atlas specimen fallback', 'Consolas, monospace'], card: ['.workspace-sidebar', '24px'], control: ['.field input, .field select', '12px'] },
};
function declarations(block) {
  return Object.fromEntries([...block.matchAll(/(?:^|;)\s*([\w-]+)\s*:\s*([^;]+)\s*(?=;|$)/g)].map(([, name, value]) => [name, value.trim()]));
}
function resolveValue(value, values) {
  let result = value;
  for (let i = 0; i < 8 && /var\(/.test(result); i++) result = result.replace(/var\((--[\w-]+)\)/g, (_, key) => {
    assert.ok(values[key], 'Missing source variable ' + key);
    return values[key];
  });
  assert.ok(!/var\(/.test(result), 'Unresolved source value ' + result);
  return result;
}
const profiles = [];
const css = ['/* Generated by tools/style-tokens.mjs. Source hashes and mappings: theme-tokens.json. */'];
for (const theme of catalog.themes) {
  assert.ok(config[theme.id], 'Add an explicit projection for new theme ' + theme.id);
  const source = 'themes/' + theme.id + '/preview/styles.css';
  const bytes = await readFile(path.join(root, source));
  const text = bytes.toString('utf8');
  const lightMatch = /:root\s*\{([^}]+)\}/.exec(text);
  const darkMatch = /:root\[data-appearance=["']dark["']\]\s*\{([^}]+)\}/.exec(text);
  assert.ok(lightMatch && darkMatch, 'Expected explicit appearance blocks for ' + theme.id);
  const base = declarations(lightMatch[1]);
  const modes = { light: base, dark: { ...base, ...declarations(darkMatch[1]) } };
  const maps = {};
  const tokens = {};
  for (const [mode, values] of Object.entries(modes)) {
    tokens[mode] = {};
    const pick = (name, candidates) => {
      const key = candidates.find(item => Object.hasOwn(values, item));
      assert.ok(key, theme.id + ': missing ' + name);
      maps[name] = { source: key };
      tokens[mode][name] = resolveValue(values[key], values);
    };
    pick('--page', ['--page']);
    pick('--surface', ['--surface']);
    pick('--raised', ['--panel', '--raised']);
    pick('--ink', ['--ink', '--text']);
    pick('--muted', ['--muted']);
    pick('--primary', ['--primary', '--action', '--accent']);
    pick('--on-primary', ['--on-primary', '--on-action', '--on-accent']);
    pick('--border', ['--control-border', '--border']);
    pick('--focus', ['--focus', '--ink', '--text']);
    pick('--error', ['--error', '--danger']);
    for (const [target, selection] of Object.entries({
      '--theme-font': config[theme.id].font, '--display-font': config[theme.id].display,
      '--mono-font': config[theme.id].mono, '--card-radius': config[theme.id].card,
      '--control-radius': config[theme.id].control,
    })) {
      if (Array.isArray(selection)) {
        const [selector, value] = selection;
        if (selector !== 'Atlas specimen fallback') {
          const blocks = text.split(selector + ' {').slice(1).map(block => block.split('}')[0]);
          assert.ok(blocks.some(block => new RegExp('border-radius:\\s*' + value.replace('.', '\\.')).test(block)), theme.id + ': source geometry changed at ' + selector);
        }
        maps[target] = { source: selector, interpretation: selector === 'Atlas specimen fallback' };
        tokens[mode][target] = value;
      } else {
        assert.ok(values[selection], theme.id + ': missing ' + selection);
        maps[target] = { source: selection };
        tokens[mode][target] = resolveValue(values[selection], values);
      }
    }
  }
  const fontFaces = [...text.matchAll(/@font-face\s*\{[^}]+\}/g)].map(match => match[0]);
  assert.ok(fontFaces.every(face => !/url\(/i.test(face)), 'Preview must not fetch font files');
  css.push(...fontFaces);
  const rule = (selector, values) => selector + ' {\n' + Object.entries(values).map(([key, value]) => '  ' + key + ': ' + value + ';').join('\n') + '\n}';
  const selector = ':root[data-theme="' + theme.id + '"]';
  css.push(rule(selector, { 'color-scheme': 'light', ...tokens.light }));
  css.push(rule(selector + '[data-appearance="dark"]', { 'color-scheme': 'dark', ...tokens.dark }));
  css.push('@media (prefers-color-scheme: dark) {\n' + rule(selector + '[data-appearance="system"]', { 'color-scheme': 'dark', ...tokens.dark }) + '\n}');
  profiles.push({ id: theme.id, name: theme.name, revision: theme.revision, creator: theme.creator,
    source: { file: source, sha256: createHash('sha256').update(bytes).digest('hex'), credits: theme.documents.sources },
    scope: 'Selected color/font/geometry projection into a shared specimen; not the complete theme or its original app.',
    mappings: maps, tokens });
}
const styleIds = ['glassmorphism', 'neobrutalism', 'claymorphism'];
const manifest = { schema_version: 1, interpretation: 'Original Atlas token projection. Source theme credits remain authoritative; system fallbacks may render instead of named fonts.', profiles };
for (const styleId of styleIds) {
  const output = path.join(root, 'styles', styleId, 'preview');
  if (!check) await mkdir(output, { recursive: true });
  for (const [name, value] of [['theme-tokens.css', css.join('\n\n') + '\n'], ['theme-tokens.json', JSON.stringify(manifest, null, 2) + '\n']]) {
    const filename = path.join(output, name);
    if (check) assert.equal(await readFile(filename, 'utf8'), value, styleId + '/' + name + ' is stale; run node tools/style-tokens.mjs');
    else await writeFile(filename, value);
  }
}
console.log((check ? 'Verified' : 'Generated') + ' bounded token projections for ' + profiles.length + ' themes across ' + styleIds.length + ' styles.');
